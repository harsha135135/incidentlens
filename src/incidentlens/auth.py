"""Browser authentication for the local developer (spec §7).

- A 32-byte access secret is generated by scripts/setup_local.py; only its SHA-256 is configured.
- Logging in exchanges it for a random server-side session with an 8-hour absolute expiry. Only
  the session token's hash is stored. The cookie is HttpOnly and SameSite=Strict.
- One canonical origin, http://127.0.0.1:8088. The Host header must match it (against DNS
  rebinding), and login and every mutation must come from that Origin.
- Mutations also need the session's CSRF token in X-CSRF-Token.
- At most 5 login attempts per minute, counted in the database so a restart does not reset it."""

from __future__ import annotations

import hashlib
import hmac
import os
import secrets
from dataclasses import dataclass

import psycopg

from incidentlens.config import INCIDENTLENS_ENV_FILE, PUBLIC_PORT, load_local_env
from incidentlens.jobs import ApiError

CANONICAL_HOST = f"127.0.0.1:{PUBLIC_PORT}"
CANONICAL_ORIGIN = f"http://{CANONICAL_HOST}"
SESSION_COOKIE = "il_session"
SESSION_HOURS = 8
LOGINS_PER_MINUTE = 5
IDENTITY = "local-developer"


@dataclass(frozen=True)
class Session:
    identity: str
    expires_at: object
    csrf_token: str


def token_hash(token: str) -> str:
    return hashlib.sha256(token.encode()).hexdigest()


def configured_secret_hash() -> str:
    load_local_env(INCIDENTLENS_ENV_FILE)
    value = os.environ.get("INCIDENTLENS_ACCESS_SECRET_SHA256", "")
    if len(value) != 64:
        raise RuntimeError("INCIDENTLENS_ACCESS_SECRET_SHA256 is not set: run scripts/setup_local.py --add-missing")
    return value


def check_host(host: str | None) -> None:
    if host != CANONICAL_HOST:
        raise ApiError(403, "BAD_HOST", f"Use {CANONICAL_ORIGIN}.")


def check_origin(origin: str | None) -> None:
    if origin != CANONICAL_ORIGIN:
        raise ApiError(403, "BAD_ORIGIN", "This request must come from the IncidentLens page.")


def login(conn: psycopg.Connection, secret: str, expected_hash: str) -> str:
    """Returns a new session token, or raises. Every attempt is counted, successful or not."""
    with conn.transaction():
        conn.execute("SELECT 1 FROM control FOR UPDATE")  # serialise attempts so the limit is exact
        recent = conn.execute("SELECT count(*) FROM login_attempts WHERE attempted_at > now() - interval '1 minute'"
                              ).fetchone()[0]
        if recent >= LOGINS_PER_MINUTE:
            raise ApiError(429, "TOO_MANY_LOGINS", "Too many login attempts; wait a minute.", True, 60)
        ok = hmac.compare_digest(token_hash(secret), expected_hash)
        conn.execute("INSERT INTO login_attempts (succeeded) VALUES (%s)", (ok,))
        if not ok:
            return ""
        token = secrets.token_urlsafe(32)
        conn.execute("INSERT INTO sessions (token_hash, identity, csrf_token, expires_at) "
                     f"VALUES (%s, %s, %s, now() + interval '{SESSION_HOURS} hours')",
                     (token_hash(token), IDENTITY, secrets.token_urlsafe(24)))
        return token


def session_for(conn: psycopg.Connection, token: str | None) -> Session:
    if not token or len(token) > 200:
        raise ApiError(401, "AUTHENTICATION_REQUIRED", "Sign in first.")
    row = conn.execute("SELECT identity, expires_at, csrf_token FROM sessions WHERE token_hash = %s "
                       "AND revoked_at IS NULL AND expires_at > now()", (token_hash(token),)).fetchone()
    if row is None:
        raise ApiError(401, "AUTHENTICATION_REQUIRED", "Your session has expired; sign in again.")
    return Session(*row)


def check_csrf(session: Session, header: str | None) -> None:
    if not header or not hmac.compare_digest(header, session.csrf_token):
        raise ApiError(403, "CSRF_REJECTED", "Missing or wrong CSRF token.")


def logout(conn: psycopg.Connection, token: str) -> None:
    with conn.transaction():
        conn.execute("UPDATE sessions SET revoked_at = now() WHERE token_hash = %s AND revoked_at IS NULL",
                     (token_hash(token),))
