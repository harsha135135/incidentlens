"""Generates local credentials into deploy/local/ (ignored by Git), each file readable only by
the current user. Prints file names, never values. Refuses to replace existing files unless
--force is given, because the databases keep the old passwords.

Files:
  ledgercore.env            LedgerCore's settings for the IncidentLens target instance
  incidentlens.env          IncidentLens database password and the read-only diagnostics login
  controller.env            Workload and fault-injection logins: used only by the evaluation
                            controller, never loaded by the gateway, the runner or the collector
  prometheus-scrape-password  The scrape login's password, mounted into the Prometheus container
  access-secret.txt         The browser login secret (only its SHA-256 is in incidentlens.env)

Usage: uv run python scripts/setup_local.py [--force | --add-missing]
"""

from __future__ import annotations

import argparse
import hashlib
import secrets
import sys
from pathlib import Path

import bcrypt

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from incidentlens.config import LOCAL_DEPLOY_DIR, TARGET_DB_PORT  # noqa: E402

BCRYPT_COST = 10  # the cost LedgerCore's README measured; the fixture consumer verifies at this cost


def new_password() -> str:
    return secrets.token_urlsafe(24)


def bcrypt_hash(password: str) -> str:
    return "{bcrypt}" + bcrypt.hashpw(password.encode(), bcrypt.gensalt(rounds=BCRYPT_COST)).decode()


def write_private(path: Path, text: str) -> None:
    path.write_text(text)
    path.chmod(0o600)


def env_text(header: str, values: dict[str, str]) -> str:
    # Single quotes keep "$" in hashes literal for the shell and for Docker Compose.
    lines = [f"# {header}", "# Generated by scripts/setup_local.py. Do not commit."]
    lines += [f"{name}='{value}'" for name, value in values.items()]
    return "\n".join(lines) + "\n"


def read_env(path: Path) -> dict[str, str]:
    values = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            name, value = line.split("=", 1)
            values[name.strip()] = value.strip().strip("'").strip('"')
    return values


def add_missing(path: Path, header: str, wanted: dict[str, callable]) -> list[str]:
    """Adds keys that are missing from an existing env file, keeping every existing value (the
    databases already use them). Returns the names added."""
    current = read_env(path)
    added = {name: make() for name, make in wanted.items() if name not in current}
    if added:
        write_private(path, env_text(header, current | added))
    return list(added)


def new_access_secret() -> str:
    """The browser login secret: 32 random bytes (spec §7). Only its SHA-256 is kept in
    incidentlens.env; the secret itself is printed once and kept in an owner-only file."""
    secret = secrets.token_urlsafe(32)
    write_private(LOCAL_DEPLOY_DIR / "access-secret.txt", secret + "\n")
    print(f"Browser access secret (shown once; also in {LOCAL_DEPLOY_DIR / 'access-secret.txt'}): {secret}")
    return hashlib.sha256(secret.encode()).hexdigest()


def incidentlens_extras() -> dict[str, callable]:
    return {
        "INCIDENTLENS_APP_DB_PASSWORD": new_password,
        "INCIDENTLENS_COLLECTOR_DB_PASSWORD": new_password,
        "INCIDENTLENS_ACCESS_SECRET_SHA256": new_access_secret,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--force", action="store_true", help="replace existing credential files")
    parser.add_argument("--add-missing", action="store_true",
                        help="add keys introduced by later stages to existing files, keeping existing values")
    args = parser.parse_args()

    names = ["ledgercore.env", "incidentlens.env", "controller.env", "prometheus-scrape-password"]
    if args.add_missing:
        added = add_missing(LOCAL_DEPLOY_DIR / "incidentlens.env", "IncidentLens", incidentlens_extras())
        print(f"added to incidentlens.env: {', '.join(added) or 'nothing (all keys present)'}")
        return 0
    existing = [name for name in names if (LOCAL_DEPLOY_DIR / name).exists()]
    if existing and not args.force:
        print(f"Already present in {LOCAL_DEPLOY_DIR}: {', '.join(existing)}. Use --add-missing to add new keys, "
              "or --force to replace them (then recreate the database volumes, which keep the old passwords).")
        return 1

    LOCAL_DEPLOY_DIR.mkdir(parents=True, exist_ok=True)
    LOCAL_DEPLOY_DIR.chmod(0o700)
    secret = {name: new_password() for name in (
        "owner", "app", "customer_a", "customer_b", "admin", "publisher", "scrape", "diag_reader", "incidentlens_db")}

    write_private(LOCAL_DEPLOY_DIR / "ledgercore.env", env_text("LedgerCore target instance", {
        "LEDGERCORE_DB_URL": f"jdbc:postgresql://127.0.0.1:{TARGET_DB_PORT}/ledgercore",
        "LEDGERCORE_DB_OWNER_USER": "ledger_owner",
        "LEDGERCORE_DB_OWNER_PASSWORD": secret["owner"],
        "LEDGERCORE_DB_APP_USER": "ledger_app",
        "LEDGERCORE_DB_APP_PASSWORD": secret["app"],
        "LEDGERCORE_CUSTOMER_A_PASSWORD_HASH": bcrypt_hash(secret["customer_a"]),
        "LEDGERCORE_CUSTOMER_B_PASSWORD_HASH": bcrypt_hash(secret["customer_b"]),
        "LEDGERCORE_ADMIN_PASSWORD_HASH": bcrypt_hash(secret["admin"]),
        "LEDGERCORE_PUBLISHER_PASSWORD": secret["publisher"],
        "LEDGERCORE_PUBLISHER_PASSWORD_HASH": bcrypt_hash(secret["publisher"]),
        "LEDGERCORE_DIAGNOSTICS_PASSWORD_HASH": bcrypt_hash(secret["scrape"]),
        "LEDGERCORE_DIAG_READER_PASSWORD": secret["diag_reader"],
    }))
    write_private(LOCAL_DEPLOY_DIR / "incidentlens.env", env_text("IncidentLens", {
        "INCIDENTLENS_DB_PASSWORD": secret["incidentlens_db"],
        "LEDGERCORE_DIAG_READER_PASSWORD": secret["diag_reader"],
        **{name: make() for name, make in incidentlens_extras().items()},
    }))
    write_private(LOCAL_DEPLOY_DIR / "controller.env", env_text("Evaluation controller only", {
        "CONTROLLER_CUSTOMER_A_PASSWORD": secret["customer_a"],
        "CONTROLLER_ADMIN_PASSWORD": secret["admin"],
        "CONTROLLER_TARGET_OWNER_PASSWORD": secret["owner"],
    }))
    write_private(LOCAL_DEPLOY_DIR / "prometheus-scrape-password", secret["scrape"])

    for name in names:
        print(f"wrote {LOCAL_DEPLOY_DIR / name} (mode 600)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
